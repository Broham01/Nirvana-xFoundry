# shellcheck shell=bash
# Shared by the dev scripts. Everything here is scoped to xFoundry: Docker Desktop, Nirvana's containers and your
# default kubectl context are never touched.
#  - Docker: commands go to xFoundry's own Colima VM through DOCKER_CONTEXT (this process only; `docker context use`
#    is never called, so your default stays Docker Desktop).
#  - Kubernetes: the cluster lives in its own kubeconfig file (platform/dev/.kubeconfig), not ~/.kube/config.
DEV_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=versions.env
source "$DEV_DIR/versions.env"
export DOCKER_CONTEXT="colima-$XFOUNDRY_VM"
export KUBECONFIG="$DEV_DIR/.kubeconfig"
CTX="kind-$KIND_CLUSTER"
k() { kubectl --context "$CTX" "$@"; }
step() { printf '\n\033[1m== %s\033[0m\n' "$1"; }
vm_running() { colima status --profile "$XFOUNDRY_VM" >/dev/null 2>&1; }
# Run a command in the VM's own namespaces (kernel modules, /dev/kvm), from a privileged throwaway container.
in_vm() { docker run --rm --privileged --pid=host docker.io/library/alpine:3.22 nsenter -t 1 -m -u -n -i -- sh -c "$1"; }

write_env() {
  arch=$(docker info --format '{{.Architecture}}')
  case "$arch" in aarch64|arm64) arch=arm64 ;; *) arch=amd64 ;; esac
  cat > "$DEV_DIR/env.sh" <<ENV
# shellcheck shell=bash
# Generated by up.sh. Source it in a shell where you use xfoundry with the dev platform:
#   source platform/dev/env.sh
# It only affects that shell.
export DOCKER_CONTEXT=$DOCKER_CONTEXT
export KUBECONFIG=$KUBECONFIG
export XFOUNDRY_KUBE_CONTEXT=$CTX
export XFOUNDRY_ARCH=$arch
ENV
}
